function buildEpisodes(
  baseId: number,
  seasonNumber: number,
  titles: string[],
  startAirDate: string,
  avgRuntime: number,
  unairedFromIdx: number = 999
): EpisodeItem[] {
  const [startYear, startMonth, startDay] = startAirDate.split('-').map(Number);
  return titles.map((name, idx) => {
    const isUnaired = idx >= unairedFromIdx;
    const d = isUnaired
      ? new Date(2026, 10, 27 + (idx - unairedFromIdx) * 7)
      : new Date(startYear, startMonth - 1, startDay + idx * 7);
    const y = d.getFullYear();
    const m = String(d.getMonth() + 1).padStart(2, '0');
    const day = String(d.getDate()).padStart(2, '0');
    return {
      id: baseId * 1000 + seasonNumber * 100 + idx + 1,
      seasonNumber,
      episodeNumber: idx + 1,
      name,
      overview: isUnaired
        ? 'Scheduled upcoming episode. Check back after broadcast.'
        : `Chapter ${idx + 1} of Season ${seasonNumber} continues the arc with new revelations and shifting stakes.`,
      airDate: `${y}-${m}-${day}`,
      runtime: avgRuntime + ((idx % 3) - 1) * 4,
      stillPath: null,
    };
  });
}

